# 프로젝트 주제: 건축 공간 속에 조명 추천
# ------------------------------------------------------------
# 1. 데이터 준비: 2차원 리스트
# ------------------------------------------------------------
# 0번 열: 건축 공간 종류
# 1번 열: 적정 조도 기준 (단위: Lux)
# ------------------------------------------------------------
space_lux_list = [
    ["침실", 150],
    ["거실", 300],
    ["공부방", 500],
    ["부엌", 250],
]

# ------------------------------------------------------------
# 2. 함수 정의
# ------------------------------------------------------------

def show_intro():
    """프로그램 제목과 안내를 출력한다."""
    print("🏢 건축 공간별 적정 조명(밝기) 추천 프로그램")
    print("= 실내 건축 설계 시 필요한 형광등 개수 계산기 =")


def get_user_input():
    """사용자에게 공간 종류와 방의 면적을 입력받는다."""
    space_name = input("조사할 공간의 이름을 입력하세요 (침실, 거실, 공부방, 부엌): ")
    area = float(input("해당 공간의 면적을 제곱미터(m²) 단위로 입력하세요: "))
    return space_name, area


def find_lux(data, space_name):
    """2차원 리스트를 반복하며 사용자가 입력한 공간의 Lux 값을 찾는다."""
    # for문을 사용하여 2차원 리스트를 한 줄(행)씩 꺼냅니다.
    for row in data:
        # 만약 리스트의 0번 열(공간 이름)이 사용자가 입력한 이름과 같다면
        if row[0] == space_name:
            return row[1]  # 1번 열에 있는 Lux(조도) 값을 반환합니다.
            
    return 0  # 리스트를 다 돌았는데 못 찾았다면 0을 반환합니다.


def print_result(space_name, area, lux):
    """최종 추천 결과를 계산하고 출력한다."""
    print("\n[추천 결과]")

    # 예외 처리: 리스트에서 공간을 찾지 못한 경우 (lux가 0인 경우)
    if lux == 0:
        print("❌ 오류: 등록되지 않은 공간입니다.")
        print("목록에 있는 공간(침실, 거실, 공부방, 부엌)을 정확히 입력해 주세요.")
    else:
        # 건축 조도 계산 공식 활용
        # 필요 총 밝기(루멘, lm) = 면적(m²) * 조도(Lux)
        total_lumen = area * lux
        
        # 일자형 형광등 1개 밝기(2000루멘)로 나누어 필요한 개수 계산 (버림 연산 //)
        lamp_count = int(total_lumen // 2000)
        
        # 나머지가 있으면 빛이 부족하므로 형광등 1개를 더 추가 (올림 처리 조건문)
        if total_lumen % 2000 > 0:
            lamp_count += 1

        print(f"- 선택하신 공간: {space_name}")
        print(f"- 공간의 적정 조도: {lux} Lux")
        print(f"- 입력하신 면적: {area} m²")
        print(f"- 이 공간에 필요한 총 밝기: {total_lumen} lm")
        print("-" * 40)
        print(f"💡 추천 결과: 일자형 형광등(2000lm) 총 **{lamp_count}개**가 필요합니다.")
    print("=" * 40)


def main():
    show_intro()  # 1. 안내문 출력
    space_name, area = get_user_input()  # 2. 사용자 입력 받기
    lux = find_lux(space_lux_list, space_name)  # 3. 2차원 리스트에서 조도 찾기
    print_result(space_name, area, lux)  # 4. 결과 계산 및 출력


# ------------------------------------------------------------
# 3. 프로그램 실행
# ------------------------------------------------------------
main()